# ---------------- answer + judge ----------------


class Chat:
    def __init__(self, settings: Settings | None = None) -> None:
        import httpx

        self.s = settings or Settings()
        self._http = httpx.Client(timeout=180)

    def complete(self, messages: list[dict], json_mode: bool = False) -> tuple[str, dict]:
        token = credential().get_token(OPENAI_SCOPE).token
        body: dict[str, Any] = {"model": self.s.chat_deployment, "messages": messages}
        if json_mode:
            body["response_format"] = {"type": "json_object"}
        r = self._http.post(
            f"{self.s.model_endpoint}/openai/v1/chat/completions",
            headers={"Authorization": f"Bearer {token}"},
            json=body,
        )
        r.raise_for_status()
        d = r.json()
        return d["choices"][0]["message"]["content"], d.get("usage", {})


ANSWER_SYSTEM = (
    "You answer questions about Kestrel Consulting's projects using ONLY the provided context. "
    "Be complete: list every matching item you find, with names. If the context doesn't contain the answer, say so. "
    "Context may include graph query results (columns and rows). A graph query that filters on a specific "
    "relationship and returns no rows means that relationship doesn't exist: answer such questions with 'No'. "
    "Answer in at most 300 words."
)


def answer(chat: Chat, question: str, retrieval: Retrieval) -> tuple[str, dict]:
    ctx = "\n\n".join(f"[{i + 1}] ({c['source']})\n{c['text']}" for i, c in enumerate(retrieval.context))
    return chat.complete(
        [
            {"role": "system", "content": ANSWER_SYSTEM},
            {"role": "user", "content": f"Context:\n{ctx}\n\nQuestion: {question}"},
        ]
    )


JUDGE_SYSTEM = (
    "You grade an answer against an expected answer and a list of required facts. "
    'Return JSON: {"facts": [{"fact": str, "present": bool}], "correct": bool, "note": str}. '
    "A fact is present if the answer states it, even in other words. "
    "correct is true only if the answer's main claim matches the expected answer and contains no wrong items."
)


def judge(chat: Chat, q: dict, ans: str) -> dict:
    content, _ = chat.complete(
        [
            {"role": "system", "content": JUDGE_SYSTEM},
            {
                "role": "user",
                "content": json.dumps(
                    {
                        "question": q["question"],
                        "expected_answer": q["answer"],
                        "required_facts": q["required_facts"],
                        "answer": ans,
                    },
                    ensure_ascii=False,
                ),
            },
        ],
        json_mode=True,
    )
    return json.loads(content)
