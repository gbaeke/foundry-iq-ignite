"""Retrieval strategies compared on the same question.

Every strategy returns the context it retrieved plus retrieval metadata. The answer is then
generated by the same chat model for all strategies, so differences come from retrieval only.
"""

from __future__ import annotations

import json
import time
from collections.abc import Callable
from dataclasses import dataclass, field
from typing import Any

from kestrel_kg.client import SearchClient, Settings, credential
from kestrel_kg.graphs import GRAPHS

CHUNK_INDEX = "kestrel-entities-ks-index"
ENTITY_KB = "kestrel-entities-kb"
ENTITY_KS = "kestrel-entities-ks"

OPENAI_SCOPE = "https://cognitiveservices.azure.com/.default"


@dataclass
class Retrieval:
    strategy: str
    context: list[dict[str, Any]]  # [{"source": str, "text": str}]
    latency_ms: int
    retrieval_tokens: int = 0  # tokens spent by the retrieval engine itself (planning, graph queries)
    debug: dict[str, Any] = field(default_factory=dict)


def _source_name(url: str | None) -> str:
    return (url or "").split("/kestrel-corpus/")[-1] or "?"


# ---------------- strategies ----------------


def rag(c: SearchClient, question: str, top: int = 5) -> Retrieval:
    """Hybrid (BM25 + vector) with semantic reranking: the strong 'plain RAG' baseline."""
    t = time.perf_counter()
    r = c.post(
        f"/indexes('{CHUNK_INDEX}')/docs/search",
        {
            "search": question,
            "vectorQueries": [{"kind": "text", "text": question, "fields": "snippet_vector", "k": 50}],
            "queryType": "semantic",
            "semanticConfiguration": "kestrel-entities-ks-semantic-configuration",
            "select": "uid,snippet,blob_url",
            "top": top,
        },
    )
    ctx = [{"source": _source_name(d.get("blob_url")), "text": d["snippet"]} for d in r["value"]]
    return Retrieval("rag", ctx, int((time.perf_counter() - t) * 1000))


def agentic(c: SearchClient, question: str, top: int = 10) -> Retrieval:
    """Direct search with queryType=agentic: Microsoft Retriever 1 plans and rewrites queries.

    Runs on the same chunk index as `rag`, so both strategies see identical passages.
    """
    t = time.perf_counter()
    r = c.post(
        f"/indexes('{CHUNK_INDEX}')/docs/search",
        {
            "search": question,
            "queryType": "agentic",
            "agenticOptions": {"maxRuntimeInSeconds": 60},
            "select": "uid,snippet,blob_url",
            "top": top,
            "debug": "agentic",
        },
    )
    dbg = (r.get("@search.debug") or {}).get("agentic") or {}
    usage = dbg.get("usage") or {}
    ctx = [{"source": _source_name(d.get("blob_url")), "text": d["snippet"]} for d in r["value"]]
    return Retrieval(
        "agentic",
        ctx,
        int((time.perf_counter() - t) * 1000),
        retrieval_tokens=sum(v for v in usage.values() if isinstance(v, int)),
        debug={"subQueries": dbg.get("subQueries"), "terminationReason": dbg.get("terminationReason")},
    )


def _kb_retrieve(
    c: SearchClient, kb: str, ks: str, kind: str, question: str, extra: dict, effort: str | None = None
) -> tuple[dict, int]:
    t = time.perf_counter()
    body: dict[str, Any] = {
        "messages": [{"role": "user", "content": [{"type": "text", "text": question}]}],
        "includeActivity": True,
        "outputMode": "extractiveData",
        "maxRuntimeInSeconds": 60,
        "knowledgeSourceParams": [
            {"kind": kind, "knowledgeSourceName": ks, "includeReferences": True, "includeReferenceSourceData": True}
            | extra
        ],
    }
    if effort:
        body["retrievalReasoningEffort"] = {"kind": effort}
    r = c.post(f"/knowledgebases('{kb}')/retrieve", body)
    return r, int((time.perf_counter() - t) * 1000)


def _activity_tokens(activity: list[dict]) -> int:
    return sum((a.get("inputTokens") or 0) + (a.get("outputTokens") or 0) for a in activity)


def _references_to_context(r: dict) -> list[dict]:
    ctx: list[dict] = []
    for ref in r.get("references", []):
        sd = ref.get("sourceData") or {}
        text = sd.get("snippet") or sd.get("content") or json.dumps(sd, ensure_ascii=False)
        ctx.append(
            {"source": _source_name(sd.get("blob_url")) if sd.get("blob_url") else ref.get("type", "?"), "text": text}
        )
    # The extracted response carries graph rows as well; keep it so graph answers are not lost.
    for item in r.get("response", []):
        for content in item.get("content", []):
            if content.get("text"):
                ctx.insert(0, {"source": "knowledge-base-response", "text": content["text"]})
    return ctx


def entity(
    c: SearchClient,
    question: str,
    kb: str = ENTITY_KB,
    ks: str = ENTITY_KS,
    effort: str | None = None,
    name: str = "entity",
) -> Retrieval:
    """Knowledge base over the entity graph: planner mixes text search and generated GQL."""
    r, ms = _kb_retrieve(
        c,
        kb,
        ks,
        "azureBlob",
        question,
        {
            "graphParameters": {
                "includeQuery": True,
                "provenance": {
                    "kind": "hydrate",
                    "hydrateDocuments": {"select": "uid,snippet,snippet_parent_id,blob_url", "top": 10},
                },
            }
        },
        effort,
    )
    activity = r.get("activity", [])
    gql = [a.get("query") or a.get("graphQuery") for a in activity if "graph" in (a.get("type") or "").lower()]
    return Retrieval(
        name, _references_to_context(r), ms, _activity_tokens(activity), {"activity": activity, "gql": gql}
    )


def _hybrid(c: SearchClient, question: str, top: int, topic_graph: dict | None, name: str) -> Retrieval:
    t = time.perf_counter()
    vq: dict[str, Any] = {"kind": "text", "text": question, "fields": "snippet_vector", "k": 50}
    if topic_graph:
        vq["topicGraph"] = topic_graph
    r = c.post(
        f"/indexes('{CHUNK_INDEX}')/docs/search",
        {
            "search": question,
            "vectorQueries": [vq],
            "queryType": "semantic",
            "semanticConfiguration": "kestrel-entities-ks-semantic-configuration",
            "select": "uid,snippet,blob_url",
            "top": top,
        },
    )
    ctx = [{"source": _source_name(d.get("blob_url")), "text": d["snippet"]} for d in r["value"]]
    return Retrieval(name, ctx, int((time.perf_counter() - t) * 1000))


def rag10(c: SearchClient, question: str) -> Retrieval:
    """Same hybrid query as `rag`, but 10 passages: the fair baseline for `topic`."""
    return _hybrid(c, question, 10, None, "rag10")


def topic(c: SearchClient, question: str) -> Retrieval:
    """Hybrid search with topic-diverse sampling: candidates are drawn across topics, not only the closest matches.

    The topic graph is bound to snippet_vector with stored default `none`, so it only activates here.
    """
    return _hybrid(c, question, 10, {"kind": "diverse", "diversityFactor": 0.5, "minDiversityPoolSize": 250}, "topic")


def kb_strategy(graph_id: str, name: str) -> Callable[[SearchClient, str], Retrieval]:
    """The managed knowledge base over one graph, at medium effort (it does graph and text search together)."""
    g = GRAPHS[graph_id]
    return lambda c, q: entity(c, q, g.knowledge_base, g.knowledge_source, "medium", name)


def agent_strategy(graph_id: str, name: str) -> Callable[[SearchClient, str], Retrieval]:
    """Our own GQL agent over one graph."""
    g = GRAPHS[graph_id]

    def run(c: SearchClient, q: str) -> Retrieval:
        from kestrel_kg.gql_agent import gql_agent  # gql_agent imports this module, so import late

        return gql_agent(c, q, g.graph_index, g.chunk_index, name, g.ontology_file)

    return run


